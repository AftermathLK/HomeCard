import { memo, useMemo } from 'react';
import clsx from 'clsx';
import { getBuiltinOrnament, getOccasion, type CardProject, type Surface } from '@homecard/shared';
import { useAssets } from '@/lib/assets';
import { CardSurface, RenderEnvContext, type RenderEnv } from '@/render/CardSurface';

const PX = 96;

/**
 * A scaled, trimmed preview of one card surface — the exact same renderer used by the editor
 * and the 300 DPI exporter, just CSS-scaled down.
 */
export const MiniCard = memo(function MiniCard({
  project,
  surface,
  width,
  height,
  className,
  showEmptySlots = true,
  shadow = true,
}: {
  project: CardProject;
  surface: Surface;
  /** Box to fit into (px). The card keeps its aspect ratio. */
  width: number;
  height?: number;
  className?: string;
  showEmptySlots?: boolean;
  shadow?: boolean;
}) {
  const packs = useAssets((s) => s.packs);
  const f = project.format;
  const cw = f.widthIn * PX, ch = f.heightIn * PX;
  const scale = Math.min(width / cw, height ? height / ch : Infinity);
  const env = useMemo<RenderEnv>(() => ({ mode: 'editor', dpi: 96, showEmptySlots }), [showEmptySlots]);
  return (
    <div
      className={clsx('relative shrink-0 overflow-hidden bg-white', shadow && 'shadow-card', className)}
      style={{ width: Math.round(cw * scale), height: Math.round(ch * scale) }}
    >
      <div style={{ position: 'absolute', left: 0, top: 0, transform: `scale(${scale})`, transformOrigin: '0 0', pointerEvents: 'none' }}>
        <RenderEnvContext.Provider value={env}>
          <CardSurface project={project} surface={surface} packs={packs} />
        </RenderEnvContext.Provider>
      </div>
    </div>
  );
});

/** Occasion glyph: the occasion's first built-in ornament, drawn in currentColor. */
export function OccasionGlyph({ occasionId, size = 22, className }: { occasionId: string; size?: number; className?: string }) {
  const occ = getOccasion(occasionId);
  const def = occ.ornaments.map((id) => getBuiltinOrnament(id)).find((d) => d && !d.stretch && d.kind !== 'divider');
  if (!def) return <span className={className} style={{ width: size, height: size, display: 'inline-block' }} />;
  return (
    <span
      className={clsx('inline-block shrink-0', className)}
      style={{ width: size, height: size, ['--hc-orn2' as any]: 'currentColor' }}
      // Built-in artwork generated by HomeCard itself (not user content).
      dangerouslySetInnerHTML={{ __html: def.svg }}
    />
  );
}
